#include <stdio.h>

int main(void) {
    char input[11];
    // 각 알파벳(a-z)에 대응하는 모스부호 2차원 배열
    char morse[][5] = {
        ".-", "-...", "-.-.", "-..", "."        // a, b, c, d, e
        , "..-.", "--.", "....", "..", ".---"   // f, g, h, i, j
        , "-.-", ".-..", "--", "-.", "---"      // k, l, m, n, o
        , ".--.", "--.-", ".-.", "...", "-"     // p, q, r, s, t
        , "..-", "...-", ".--", "-..-", "-.--"  // u, v, w, x, y
        , "--.."                                // z
    };
    int i;

    printf("모스부호로 변환할 단어(10자 이하의 영소문자)를 입력하세요.>");
    scanf("%10s", input);

    // 문자열의 끝('\0')을 만날 때까지 반복
    for (i = 0; input[i] ; i++) {
        // 입력된 문자에서 'a'를 빼서 인덱스 계산 (예: 'b' - 'a' = 1)
        printf("%s", morse[input[i] - 'a']);
    }
    printf("\n");

    return 0;
}